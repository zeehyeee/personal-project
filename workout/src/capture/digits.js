const MAX_DIST = Math.round(GW * GH * 0.22); // 이보다 다르면 숫자가 아니라고 본다

function hamming(a, b) {
  let d = 0;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) d++;
  return d;
}

// 이진 이미지(한 칸) → '09:24' / '6' / null
export function readDigits(bin) {
  const boxes = glyphBoxes(bin).filter((b) => (b.x1 - b.x0) * (b.y1 - b.y0) > 4);
  if (!boxes.length) return null;
  const hmax = Math.max(...boxes.map((b) => b.y1 - b.y0));
  let out = '';
  for (const b of boxes) {
    const h = b.y1 - b.y0;
    if (h < hmax * 0.3) continue; // 점·잡티
    // 콜론: 키가 작고 가운데가 비어 있다
    const midRow = Math.floor((b.y0 + b.y1) / 2);
    let midInk = false;
    for (let x = b.x0; x < b.x1; x++) if (bin.data[midRow * bin.width + x] === 0) midInk = true;
    if (h < hmax * 0.8 && !midInk) { out += ':'; continue; }
    const bits = glyphBits(bin, b);
    let best = null, bestD = Infinity;
    for (const [d, t] of Object.entries(DIGIT_TEMPLATES)) {
      const dist = hamming(bits, t);
      if (dist < bestD) { bestD = dist; best = d; }
    }
    if (bestD > MAX_DIST) return null;
    out += best;
  }
  return out || null;
}
